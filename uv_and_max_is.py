import re
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# Model Parameters

Delta = 0.1
time_steps = 300

A_0 = 0
R_0 = 1
I_0 = 0
S_0 = 0

beta = 0.001
delta_1 = 0.5
delta_2 = 0.5
p = 1
rho = 0.1
xi = 0.004
gamma = 0.008

u_values = np.linspace(0, 1, 101)

max_S_values = []
max_I_values = []

for u in u_values:

    A = A_0
    R = R_0
    I = I_0
    S = S_0

    R_history = [R]
    I_history = [I]
    S_history = [S]
    A_history = [A]

    for n in range(time_steps):

        A_next = (
        A
        + 0.1 * (
            xi - gamma*A
        )
        )
        R_next = (
            R
            + 0.1 * (
                -delta_1*p*A*R - delta_2*p*u*A*R + beta*S
            )
        )
        I_next = (
            I
            + 0.1 * (
                delta_1*p*A*R + delta_2*p*u*A*R - rho*I
            )
        )
        S_next = (
            S
            + 0.1 * (
                rho*I - beta*S
            )
        )

        R, I, S, A = R_next, I_next, S_next, A_next

        R_history.append(R)
        I_history.append(I)
        S_history.append(S)
        A_history.append(A)

    max_S_values.append(np.max(S_history))
    max_I_values.append(np.max(I_history))

plt.figure(figsize=(10, 6))

plt.plot(
    u_values,
    max_S_values,
    label='$Sensitivity$',
    color='red',
    linewidth=2
)

plt.plot(
    u_values,
    max_I_values,
    label='$Inflammation$',
    color='green',
    linewidth=2
)

plt.xlabel('$u$ (UV Exposure)', fontsize=14)
plt.ylabel('Maximum value', fontsize=14)

plt.title(
    'Maximum Sensitivity and Inflammation in 30 Weeks vs UV Exposure Levels',
    fontsize=15
)

plt.xlim(0, 1)
plt.ylim(bottom=0)

plt.legend(fontsize=12)
plt.grid(True, alpha=0.3)

plt.tight_layout()
plt.show()

