import re
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

A_0 = 0
R_0 = 1
I_0 = 0
S_0 = 0

y0 = [A_0, R_0, I_0, S_0]

beta = 0.001
delta_1 = 0.5
delta_2 = 0.5
u = 0.1
p = 0.005
rho = 0.1
xi = 0.004
gamma = 0.008

parameters_real = {
    "beta": beta,
    "delta_1": delta_1,
    "delta_2": delta_2,
    "u": u,
    "p": p,
    "rho": rho,
    "xi": xi,
    "gamma": gamma,
}

n_steps = 1500
noise_levels = [0.01, 0.05, 0.10, 0.20]

def generate_data(t_array, y0, beta, delta_1, delta_2, u, p, rho, xi, gamma):
  n_steps = len(t_array)
  states = np.zeros((n_steps, len(y0)))
  states[0] = y0

  for n in range(n_steps - 1):
    A, R, I, S = states[n]

    A_next = (
        A
        + 0.1 * (
            xi - gamma*A
        )
    )
    R_next = (
        R
        + 0.1 * (
            -delta_1*p*A*R - delta_2*p*u*A*R + beta*S
        )
    )
    I_next = (
        I
        + 0.1 * (
            delta_1*p*A*R + delta_2*p*u*A*R - rho*I
        )
    )
    S_next = (
        S
        + 0.1 * (
            rho*I - beta*S
        )
    )
    states[n+1] = [
        A_next,
        R_next,
        I_next,
        S_next,
    ]
  return states

# Generate the clean synthetic data
t_train = np.arange(0, n_steps + 1)[:, np.newaxis]

y_clean = generate_data(
    np.ravel(t_train),
    y0,
    beta,
    delta_1,
    delta_2,
    u,
    p,
    rho,
    xi,
    gamma
)

for noise_val in noise_levels:
    print(f"Generating synthetic data with noise level: {noise_val*100:.0f}%")

    y_noisy = y_clean + (
        np.random.normal(
            loc=0,
            scale=y_clean.std(axis=0),
            size=y_clean.shape
        ) * noise_val
    )

    names = ["A", "R", "I", "S"]

    data_real = (
        pd.DataFrame(y_noisy, columns=names, index=t_train.ravel())
        .rename_axis("time")
        .reset_index()
        .melt(id_vars="time", var_name="status", value_name="skin")
    )

    fig, ax = plt.subplots(figsize=(7, 5))

    sns.lineplot(
        x="time",
        y="skin",
        hue="status",
        marker="o",
        linewidth=.5,
        markersize=3,
        markeredgecolor=None,
        data=data_real,
        ax=ax
    )

    ax.set(title=f"Synthetic Data with {noise_val*100:.0f}% Noise")
    fig.savefig("donkeysyntheticdata-noiseval" + str(noise_val) + ".png")
    fig.show()